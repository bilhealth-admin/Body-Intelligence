  final language = locale.split(RegExp('[-_]')).first;
  return _dailyCheckInCopy[key]?[locale] ??
      _dailyCheckInCopy[key]?[language] ??
      CheckInRuntimeCopy.resolve(key, locale) ??
      _dailyCheckInCopy[key]?['en'] ??
      key;
}

