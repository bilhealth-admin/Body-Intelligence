String? communityMediaText(String localeTag, String english) {
  final index = communityMediaEnglishKeys.indexOf(english);
  if (index < 0) return null;
  final translations = communityMediaLocaleCopy[localeTag];
  if (translations == null ||
      translations.length != communityMediaEnglishKeys.length) {
    return null;
  }
  return translations[index];
}
