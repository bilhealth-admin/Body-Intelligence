/// Reviewed phonetic building blocks for Arabic workout discovery titles.
///
/// These are transliterations of the canonical English names, not literal
/// translations of movement meaning. Unknown tokens fail closed so a newly
/// added exercise cannot silently receive a guessed or misleading title.
