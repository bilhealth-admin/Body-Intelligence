  static String transliterate(String canonicalEnglishTitle) {
    final tokens = canonicalEnglishTitle
        .toLowerCase()
        .split(RegExp('[^a-z]+'))
        .where((token) => token.isNotEmpty);
    final output = <String>[];
    for (final token in tokens) {
      if (token == 's') {
        if (output.isEmpty) {
          throw const FormatException('Invalid possessive workout title.');
        }
        output[output.length - 1] = '${output.last}ز';
        continue;
      }
      final transliteration = _tokens[token];
      if (transliteration == null) {
        throw FormatException(
          'Missing Arabic workout transliteration token: $token.',
        );
      }
      output.add(transliteration);
    }
    if (output.isEmpty) {
      throw const FormatException('Workout title cannot be transliterated.');
    }
    return output.join(' ');
  }

