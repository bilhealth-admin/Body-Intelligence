  static String? resolve(String source, String? localeTag) {
    final index = sources.indexOf(source);
    if (index < 0 || localeTag == null) return null;
    final row = rows[localeTag];
    if (row == null || row.length != sources.length) return null;
    return row[index];
  }

  static bool get balanced =>
      rows.keys.toSet().containsAll(BilLocalePolicy.productionTags) &&
      BilLocalePolicy.productionTags.containsAll(rows.keys) &&
      rows.entries.every(
        (entry) =>
            entry.value.length == sources.length &&
            entry.value.asMap().entries.every(
              (value) =>
                  value.value.trim().isNotEmpty &&
                  (entry.key == 'en' || value.value != sources[value.key]),
            ),
      );
}
