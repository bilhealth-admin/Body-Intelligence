  static String? resolve(String source, String localeTag) {
    final index = sources.indexOf(source);
    if (index < 0) return null;
    final tag = BilLocalePolicy.canonicalSupportedTag(localeTag);
    if (tag == null) return null;
    final row = rows[tag];
    if (row == null || row.length != sources.length) {
      throw StateError('Missing AI safety report copy for $tag.');
    }
    return row[index];
  }

  static bool get balanced => validationIssues.isEmpty;

  static List<String> get validationIssues {
    final issues = <String>[];
    final productionTags = BilLocalePolicy.productionTags.toSet();
    final rowTags = rows.keys.toSet();
    if (supported.length != productionTags.length ||
        !supported.containsAll(productionTags) ||
        !productionTags.containsAll(supported)) {
      issues.add('Supported locales do not match production locales.');
    }
    if (rowTags.length != supported.length ||
        !rowTags.containsAll(supported) ||
        !supported.containsAll(rowTags)) {
      issues.add('Translation rows do not match supported locales.');
    }
    final english = rows['en'];
    if (english == null || english.length != sources.length) {
      issues.add('English row does not match the source count.');
    } else {
      for (var index = 0; index < sources.length; index++) {
        if (english[index] != sources[index]) {
          issues.add('English source mismatch at index $index.');
        }
      }
    }
    for (final tag in supported) {
      final row = rows[tag];
      if (row == null) {
        issues.add('$tag: translation row is missing.');
        continue;
      }
      if (row.length != sources.length) {
        issues.add(
          '$tag: ${row.length} entries for ${sources.length} sources.',
        );
        continue;
      }
      for (var index = 0; index < row.length; index++) {
        if (row[index].trim().isEmpty) {
          issues.add('$tag: empty translation at index $index.');
          break;
        }
        if (tag != 'en' && row[index] == sources[index]) {
          issues.add(
            '$tag: untranslated source at index $index (${sources[index]}).',
          );
        }
      }
      if (!_placeholdersMatch(row)) {
        issues.add('$tag: placeholder mismatch.');
      }
    }
    return List<String>.unmodifiable(issues);
  }

  static bool _placeholdersMatch(List<String> row) {
    for (var index = 0; index < sources.length; index++) {
      final expected = _placeholders(sources[index]);
      final actual = _placeholders(row[index]);
      if (expected.length != actual.length) return false;
      for (var i = 0; i < expected.length; i++) {
        if (expected[i] != actual[i]) return false;
      }
    }
    return true;
  }

  static List<String> _placeholders(String value) => RegExp(
    r'\{[^}]+\}',
  ).allMatches(value).map((match) => match.group(0)!).toList(growable: false);
