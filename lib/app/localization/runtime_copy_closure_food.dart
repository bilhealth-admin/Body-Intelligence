  static String? resolve(String source, String tag) {
    // The SI symbol stays g in the other supported locales; Arabic uses the
    // same reviewed mass symbol as measured-value formatting. A unit is not an
    // untranslated sentence and must not emit a missing-copy diagnostic.
    if (source == 'g') {
      return BilLocalePolicy.localeFromTag(tag).languageCode == 'ar'
          ? 'غ'
          : 'g';
    }
    final i = sources.indexOf(source);
    if (i < 0) return null;
    return rows[BilLocalePolicy.canonicalTag(
      BilLocalePolicy.localeFromTag(tag),
    )]?[i];
  }

  static bool get balanced =>
      rows.length == 25 &&
      rows.values.every(
        (r) =>
            r.length == sources.length && r.every((s) => s.trim().isNotEmpty),
      );
