  static String? resolve(String english, String localeTag) {
    final index = sources.indexOf(english);
    if (index < 0) return null;
    final tag = BilLocalePolicy.canonicalSupportedTag(localeTag);
    final row = translations[tag];
    return row == null ? null : row[index];
  }

  static bool get balanced {
    final required = BilLocalePolicy.productionTags;
    if (translations.length != required.length ||
        !translations.keys.toSet().containsAll(required)) {
      return false;
    }
    for (final tag in required) {
      final row = translations[tag];
      if (row == null || row.length != sources.length) return false;
      for (var i = 0; i < sources.length; i++) {
        if (row[i].trim().isEmpty || (tag != 'en' && row[i] == sources[i])) {
          return false;
        }
      }
    }
    return true;
  }
