import prepare_local_supabase_ci_stack as h

SOURCE="""# Generated by pinned CLI; no checked-in config is used.
project_id = "Body-Intelligence" # keep comment
[api]
port = 54321
schemas = ["public", "storage", "graphql_public"]
[db]
port = 54322 # host database only
shadow_port = 54320
major_version = 17
[auth]
enabled = true
site_url = "http://localhost:3000"
[edge_runtime]
enabled = true
"""

class LocalPortsTest(unittest.TestCase):
    def allocation(self,db=54322):
        selected=dict(h.DEFAULTS);selected[('db','port')]=db
        return selected,{k:selected[k]!=v for k,v in h.DEFAULTS.items()}

    def test_free_defaults_keep_ports_and_scope_change_to_unique_owned_project(self):
        result,report=h.prepare(SOURCE,'123','2',allocator=self.allocation)
        before=tomllib.loads(SOURCE);expected=copy.deepcopy(before);expected['project_id']='bil-ci-123-2'
        self.assertEqual(tomllib.loads(result),expected)
        self.assertIn('# keep comment',result)
        self.assertEqual(report['exact_database_container'],'supabase_db_bil-ci-123-2')

    def test_busy_database_port_changes_only_that_port_and_owned_id(self):
        result,report=h.prepare(SOURCE,'123','2',allocator=lambda:self.allocation(61002))
        expected=tomllib.loads(SOURCE);expected['project_id']='bil-ci-123-2';expected['db']['port']=61002
        self.assertEqual(tomllib.loads(result),expected)
        self.assertTrue(next(x for x in report['ports'] if x['field']=='db.port')['original_port_busy'])
        self.assertEqual(tomllib.loads(result)['auth'],tomllib.loads(SOURCE)['auth'])

    def test_unknown_config_or_hosted_project_is_refused_before_allocation(self):
        for source in [SOURCE.replace('Body-Intelligence','other-project'),SOURCE.replace('port = 54322','port = 50000'),SOURCE+'\n[db]\nport = 54322\n']:
            with self.subTest(source=source),self.assertRaises((ValueError,tomllib.TOMLDecodeError)):
                h.prepare(source,'123','2',allocator=lambda:self.fail('Must not allocate'))

    def test_run_identifiers_cannot_inject_container_or_environment_text(self):
        for run,attempt in [('abc','1'),('123','2\nBAD=yes'),('','1')]:
            with self.assertRaises(ValueError):h.prepare(SOURCE,run,attempt)

    def test_allocator_uses_one_fallback_on_only_eaddrinuse_and_closes_all_handles(self):
        handles=[]
        class Socket:
            def __init__(self):self.port=None;self.closed=False;handles.append(self)
            def bind(self,address):
                if address[1]==54322:raise OSError(errno.EADDRINUSE,'busy')
                self.port=address[1] or 61002
            def getsockname(self):return ('0.0.0.0',self.port)
            def close(self):self.closed=True
        chosen,busy=h.allocate_ports(factory=lambda *_:Socket())
        self.assertEqual(chosen[('db','port')],61002);self.assertTrue(busy[('db','port')])
        self.assertTrue(all(x.closed for x in handles))

    def test_non_collision_socket_error_is_not_retried_or_suppressed(self):
        class Socket:
            closed=False
            def bind(self,address):raise PermissionError(errno.EACCES,'denied')
            def close(self):self.closed=True
        handle=Socket()
        with self.assertRaises(PermissionError):h.allocate_ports(factory=lambda *_:handle)
        self.assertTrue(handle.closed)

