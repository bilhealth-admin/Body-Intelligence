CREATE OR REPLACE FUNCTION auth.uid()
 RETURNS uuid
 LANGUAGE sql
 STABLE
AS $function$
  select 
  coalesce(
    nullif(current_setting('request.jwt.claim.sub', true), ''),
    (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')
  )::uuid
$function$;
CREATE OR REPLACE FUNCTION public.bil_assert_community_publish_ready()
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_actor_id uuid := (select auth.uid());
  v_policy_version text;
begin
  if v_actor_id is null then
    raise exception using
      errcode = '42501',
      message = 'community_authentication_required';
  end if;

  if not public.bil_can_use_community() then
    raise exception using
      errcode = '42501',
      message = 'community_access_suspended';
  end if;

  v_policy_version := private.bil_assert_current_community_policy();
  return v_policy_version;
end;
$function$;
CREATE OR REPLACE FUNCTION public.bil_delete_community_post(p_post_id uuid)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_catalog'
AS $function$
declare
  v_rows integer;
begin
  if auth.uid() is null then
    raise exception 'community_authentication_required' using errcode='42501';
  end if;

  update public.bil_community_posts
  set deleted_at = pg_catalog.now(),
      media_url = null,
      media_object_path = null,
      media_mime_type = null,
      media_bytes = null,
      media_width = null,
      media_height = null,
      location_label = null
  where id = p_post_id
    and author_id = auth.uid()
    and deleted_at is null;

  get diagnostics v_rows = row_count;

  if v_rows>0 then
    delete from public.bil_community_post_media_v1
    where post_id=p_post_id;
    delete from public.bil_community_post_locations_v1
    where post_id=p_post_id;
    delete from public.bil_community_post_mentions_v1
    where post_id=p_post_id;
  end if;

  return v_rows > 0;
end
$function$;
